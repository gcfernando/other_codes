/* Keep index.html usable without JavaScript, using data.js as the source of truth. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, 'data.js'), 'utf8'), context);
const commands = vm.runInContext('COMMANDS', context);
const escape = text => String(text).replace(/[&<>"']/g, c => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[c]));
// Usage fields contain authored <code> and <br> markup. Preserve those tags,
// escaping shell syntax and every other tag instead of treating it as HTML.
const usageHTML = text => escape(text)
  .replace(/&lt;(\/?)code&gt;/g, '<$1code>')
  .replace(/&lt;br\s*\/?&gt;/g, '<br>');
const rows = commands.map(([cmd, category, description, usage]) =>
  `        <tr><td><span class="cmd-text">${escape(cmd)}</span></td>` +
  `<td><span class="cat-badge">${escape(category)}</span></td>` +
  `<td><span class="desc-text">${escape(description)}</span></td>` +
  `<td><span class="usage-text">${usageHTML(usage)}</span></td></tr>`
).join('\n');
const target = path.join(__dirname, 'index.html');
const original = fs.readFileSync(target, 'utf8');
if (!/<tbody id="tableBody">[\s\S]*<\/tbody>/.test(original)) {
  throw new Error('Cannot find command table in index.html');
}
const result = original
  .replace(/<tbody id="tableBody">[\s\S]*<\/tbody>/,
    () => `<tbody id="tableBody">\n        <!-- Generated by generate-static.cjs; edit data.js, then regenerate. -->\n${rows}\n      </tbody>`)
  .replace(/(<strong id="totalCount">)\d+(<\/strong>)/, (_, start, end) => start + commands.length + end);
if (process.argv.includes('--check')) {
  if (result !== original) throw new Error('Static command table is stale. Run node generate-static.cjs.');
} else {
  fs.writeFileSync(target, result, 'utf8');
}
console.log(`Static reference: ${commands.length} commands; ${new Set(commands.map(c => c[1])).size} categories.`);
